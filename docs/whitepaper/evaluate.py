"""Reproduce the report study or regenerate its summaries, using only stdlib."""
import argparse
import csv
import hashlib
import io
import json
import os
import platform
import random
import shlex
import statistics
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
BUILD = ROOT / '.build' / 'report'
FIELDS = ('workload', 'size', 'seed', 'operations', 'elapsed_ns', 'checksum')


def run(command):
    """Run a checked command from the repository root and capture its output."""
    result = subprocess.run(command, cwd=ROOT, text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(f'{shlex.join(map(str, command))}\n{result.stdout}{result.stderr}')
    return result.stdout.strip()


def source_hashes():
    """Hash the evaluated core, bridge, vendored headers, and study sources."""
    paths = list((ROOT / 'include').glob('*'))
    paths += [ROOT / 'src/limit_order_book_c.cpp',
              ROOT / 'benchmark/report/study.cpp', Path(__file__).resolve()]
    for name in ('binary-search-tree', 'doubly-linked-list', 'robin-map'):
        paths += list((ROOT / 'vendor' / name / 'include').rglob('*.h'))
        paths += list((ROOT / 'vendor' / name / 'include').rglob('*.hpp'))
    return {str(path.relative_to(ROOT)): hashlib.sha256(path.read_bytes()).hexdigest()
            for path in sorted(set(paths)) if path.is_file()}


def summarize(directory):
    """Write an auditable median/range summary and inline LaTeX data."""
    with (directory / 'timings.csv').open() as stream:
        rows = list(csv.DictReader(stream))
    groups = {}
    for row in rows:
        key = row['workload'], int(row['size'])
        groups.setdefault(key, []).append(int(row['elapsed_ns']) / int(row['operations']))
    summaries = []
    for (workload, size), values in sorted(groups.items()):
        summaries.append(dict(workload=workload, size=size, repeats=len(values),
                              median_ns=statistics.median(values),
                              min_ns=min(values), max_ns=max(values)))
    (directory / 'summary.json').write_text(json.dumps(summaries, indent=2) + '\n')
    table = ['% Generated by evaluate.py --summarize; ns per stated operation.']
    for row in summaries:
        name = row['workload'].replace('_', '\\_')
        table.append(f"{name} & {row['size']} & {row['median_ns']:.1f} & "
                     f"{row['min_ns']:.1f}--{row['max_ns']:.1f} \\\\")
    (directory / 'table-rows.tex').write_text('\n'.join(table) + '\n')
    values = {(r['workload'], r['size']): r for r in summaries}
    macros = ['% Generated from timings.csv by evaluate.py --summarize.']
    for name, key in [('AscLast', ('ascending', 4096)),
                      ('DescLast', ('descending', 4096)),
                      ('ShuffleLast', ('shuffled', 4096)),
                      ('PairCpp', ('existing_cpp', 4096)),
                      ('PairC', ('existing_c', 4096)),
                      ('FifoLast', ('fifo_sweep', 256)),
                      ('LevelsLast', ('level_sweep', 256)),
                      ('Clock', ('clock', 1))]:
        macros.append(f"\\newcommand{{\\Study{name}}}{{{values[key]['median_ns']:.1f}}}")
    ratio = values['ascending', 4096]['median_ns'] / values['shuffled', 4096]['median_ns']
    macros.append(f'\\newcommand{{\\StudyInsertionRatio}}{{{ratio:.1f}}}')
    for workload in ('ascending', 'descending', 'shuffled'):
        with (directory / f'{workload}.csv').open('w', newline='') as stream:
            writer = csv.writer(stream)
            writer.writerow(('size', 'median', 'minus', 'plus'))
            for row in summaries:
                if row['workload'] == workload:
                    writer.writerow((row['size'], row['median_ns'],
                                     row['median_ns'] - row['min_ns'],
                                     row['max_ns'] - row['median_ns']))
    (directory / 'results.tex').write_text('\n'.join(macros) + '\n')
    print(json.dumps(summaries, indent=2))


def evaluate(output, repeats, events, seeds, budget):
    """Build once, validate deterministically, then time in randomized order."""
    output.mkdir(parents=True, exist_ok=False)
    BUILD.mkdir(parents=True, exist_ok=True)
    if platform.system() not in ('Darwin', 'Linux'):
        raise RuntimeError('This study driver supports macOS/Linux Clang or GCC.')
    compiler = shlex.split(os.environ.get('CXX', 'c++'))
    flags = ['-std=c++14', '-O3', '-DNDEBUG', '-Wall', '-Wextra', '-pedantic']
    includes = ['-Iinclude'] + [f'-Ivendor/{name}/include' for name in
                               ('binary-search-tree', 'doubly-linked-list', 'robin-map')]
    library = BUILD / ('liblob_report.dylib' if platform.system() == 'Darwin'
                       else 'liblob_report.so')
    executable = BUILD / 'study'
    bridge = compiler + flags + includes + ['-fPIC', '-fvisibility=hidden',
        '-DLOB_C_BUILDING_LIBRARY', '-dynamiclib' if platform.system() == 'Darwin'
        else '-shared', 'src/limit_order_book_c.cpp', '-o', str(library.relative_to(ROOT))]
    rpath = '@loader_path' if platform.system() == 'Darwin' else '$ORIGIN'
    build = compiler + flags + includes + ['benchmark/report/study.cpp',
        '-L.build/report', '-llob_report', f'-Wl,-rpath,{rpath}',
        '-o', str(executable.relative_to(ROOT))]
    hashes = source_hashes()
    run(bridge)
    run(build)
    cpu = platform.processor() or platform.machine()
    memory_bytes = None
    if platform.system() == 'Darwin':
        try:
            cpu = run(['sysctl', '-n', 'machdep.cpu.brand_string'])
            memory_bytes = int(run(['sysctl', '-n', 'hw.memsize']))
        except RuntimeError:
            cpu += ' (CPU model unavailable in this execution environment)'
    metadata = dict(schema=1, captured_at_utc=datetime.now(timezone.utc).isoformat(),
        source_revision=run(['git', 'rev-parse', 'HEAD']),
        source_hashes=hashes, compiler=run(compiler + ['--version']),
        build_commands=[bridge, build], platform=platform.platform(), cpu=cpu,
        memory_bytes=memory_bytes,
        architecture=platform.machine(), python=platform.python_version(),
        repeats=repeats, check_seeds=list(range(1, seeds + 1)),
        events_per_seed=events, timing_seed=20261018, operation_budget=budget,
        protocol='One warmup per process; randomized configuration order per round; '
                 'fixed price permutation; no CPU pinning or load isolation; '
                 'fresh book per insertion/sweep batch; explicit untimed clear.',
        units={'ascending': 'ns/insertion', 'descending': 'ns/insertion',
               'shuffled': 'ns/insertion', 'existing_cpp': 'ns/add-cancel pair',
               'existing_c': 'ns/add-cancel pair', 'fifo_sweep': 'ns/market request',
               'level_sweep': 'ns/market request', 'clock': 'ns/empty timed interval'})
    checks = [json.loads(run([str(executable), 'check', str(seed), str(events)]))
              for seed in range(1, seeds + 1)]
    (output / 'checks.json').write_text(json.dumps(checks, indent=2) + '\n')
    cases = [(order, size) for order in ('ascending', 'descending', 'shuffled')
             for size in (16, 128, 1024, 4096)]
    cases += [(interface, size) for interface in ('existing_cpp', 'existing_c')
              for size in (16, 256, 4096)]
    cases += [(sweep, size) for sweep in ('fifo_sweep', 'level_sweep')
              for size in (1, 16, 256)]
    cases += [('clock', 1)]
    generator = random.Random(20261018)
    with (output / 'timings.csv').open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=('round',) + FIELDS)
        writer.writeheader()
        for repetition in range(repeats):
            generator.shuffle(cases)
            for workload, size in cases:
                text = run([str(executable), workload, str(size), '20261018', str(budget)])
                row = next(csv.DictReader(io.StringIO(text), fieldnames=FIELDS))
                writer.writerow(dict(round=repetition + 1, **row))
                stream.flush()
            print(f'Completed timing round {repetition + 1}/{repeats}', flush=True)
    if source_hashes() != hashes:
        raise RuntimeError('Evaluated sources changed during the study; discard and rerun.')
    metadata['completed_at_utc'] = datetime.now(timezone.utc).isoformat()
    (output / 'metadata.json').write_text(json.dumps(metadata, indent=2) + '\n')
    summarize(output)


def main():
    """Dispatch a fresh study run or deterministic result regeneration."""
    parser = argparse.ArgumentParser(description=__doc__)
    modes = parser.add_mutually_exclusive_group(required=True)
    modes.add_argument('--output', type=Path, help='New capture directory outside the checkout.')
    modes.add_argument('--summarize', type=Path, help='Regenerate summaries of existing raw CSV.')
    parser.add_argument('--repeats', type=int, default=9)
    parser.add_argument('--events', type=int, default=10000)
    parser.add_argument('--seeds', type=int, default=20)
    parser.add_argument('--budget', type=int, default=65536)
    args = parser.parse_args()
    if args.summarize:
        summarize(args.summarize.resolve())
    else:
        if min(args.repeats, args.events, args.seeds, args.budget) < 1:
            parser.error('All run sizes must be positive.')
        output = args.output.resolve()
        if output == ROOT or ROOT in output.parents:
            parser.error('Raw capture directories must be outside the checkout.')
        evaluate(output, args.repeats, args.events, args.seeds, args.budget)


if __name__ == '__main__':
    main()
